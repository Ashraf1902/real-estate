// Score an item against the normalized user text
function scoreItem(item: KBItem, n: string): number {
  let score = 0;
  for (const group of item.keywords) {
    const hit = group.some((k) => n.includes(k) || n === k);
    if (hit) score += 2;
  }
  // exact topic bonus
  for (const group of item.keywords) {
    for (const k of group) {
      if (n === k) score += 1;
    }
  }
  return score;
}

export function getBotReply(rawInput: string): string {
  const n = normalize(rawInput);
  if (!n) return 'اكتبلي سؤالك وأنا هساعدك 👋';

  let best: KBItem | null = null;
  let bestScore = 0;
  for (const item of KB) {
    const s = scoreItem(item, n);
    if (s > bestScore) {
      bestScore = s;
      best = item;
    }
  }

  if (best && bestScore >= 2) {
    return best.reply;
  }
  // fallback: try single-token contact/intent as a light guess
  if (n.includes('سعر') || n.includes('كام') || n.includes('بكام')) return KB.find((k) => k.id === 'price')!.reply;
  if (n.includes('حجز') || n.includes('احجز')) return KB.find((k) => k.id === 'book_how')!.reply;
  if (n.includes('دفع') || n.includes('فلوس')) return KB.find((k) => k.id === 'payment_free')!.reply;

  return FALLBACKS[Math.floor(Math.random() * FALLBACKS.length)];
}

