// Normalize Arabic text: strip diacritics, unify letters, collapse spaces, lowercase
export function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/[\u064B-\u0652\u0640]/g, '') // tashkeel + tatweel
    .replace(/[أإآا]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/[^\u0621-\u064A\u0660-\u0669a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

